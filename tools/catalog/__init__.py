"""Stock brush catalog: one module per category, listed in [MODULES].

Adding a category = a new module that exposes `CATEGORY` (id, en/ru name, brushes) and one entry in
[MODULES] below; everything else (files, index, checks) is derived from it. The JSON in
app/src/main/assets/brushes/presets is generated by `tools/gen_assets.py --only presets` and is never
edited by hand (spec/tools/m2-brush.md §5).
"""
from __future__ import annotations

import json

from . import airbrush, chalk, charcoal, erasers, markers, paints, pencils, pens

#: Categories in index order.
MODULES = (pencils, charcoal, chalk, paints, erasers, pens, markers, airbrush)

#: Prefilled mode favorites; `PAINT` up to 3 ids, `ERASE` one eraser id.
FAVORITES = {
    "PAINT": ["pencils.hb", "pencils.2b", "pencils.colored"],
    "ERASE": ["erasers.soft"],
}

CATEGORIES = [m.CATEGORY for m in MODULES]


def dump(obj: dict) -> str:
    """Pretty JSON, sorted keys, UTF-8 kept as-is and one trailing LF: a byte-stable file."""
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def brushes() -> list[dict]:
    """Every preset of the catalog, in category order, after the consistency checks."""
    out: list[dict] = []
    seen: set[str] = set()
    for cat in CATEGORIES:
        for brush in cat["brushes"]:
            bid = brush["id"]
            if bid in seen:
                raise ValueError(f"duplicate brush id {bid!r}")
            seen.add(bid)
            if not bid.startswith(cat["id"] + "."):
                raise ValueError(f"{bid}: id must start with {cat['id']!r}")
            if brush["category"] != cat["id"]:
                raise ValueError(f"{bid}: category {brush['category']!r} != {cat['id']!r}")
            if set(brush["name"]) != {"en", "ru"}:
                raise ValueError(f"{bid}: name needs exactly en and ru")
            out.append(brush)
    ids = {b["id"] for b in out}
    for mode, picks in FAVORITES.items():
        for bid in picks:
            if bid not in ids:
                raise ValueError(f"favorite {bid!r} of {mode} is not in the catalog")
    if len(FAVORITES["PAINT"]) > 3 or len(FAVORITES["ERASE"]) != 1:
        raise ValueError("PAINT holds up to 3 ids, ERASE exactly 1")
    return out


def index() -> dict:
    """The `presets/index.json` document: categories with their brush ids and the mode favorites."""
    return {
        "schema": 1,
        "categories": [
            {"id": c["id"], "name": dict(c["name"]), "brushes": [b["id"] for b in c["brushes"]]} for c in CATEGORIES
        ],
        "favorites": {mode: list(picks) for mode, picks in FAVORITES.items()},
    }


def render() -> dict[str, str]:
    """Relative path under `brushes/presets` → file text, e.g. `pencils/hb.json` and `index.json`."""
    files: dict[str, str] = {}
    for brush in brushes():
        rel = f"{brush['category']}/{brush['id'].split('.', 1)[1]}.json"
        files[rel] = dump(brush)
    files["index.json"] = dump(index())
    return files
